"""
app/models.py — SQLAlchemy Database Models for Compact Options Selling Desk
Provides persistent storage for:
- Market & OI Snapshots (OISnapshot)
- Evaluated Strategy Candidates (SignalCandidate)
- Multi-Leg Paper Positions (TradePosition & PositionLeg)
- Risk & Circuit Breaker Events (RiskAuditLog)
"""

from datetime import datetime
from zoneinfo import ZoneInfo
from app.extensions import db

IST = ZoneInfo("Asia/Kolkata")


class OISnapshot(db.Model):
    """Timestamped Open Interest and Market Structure Snapshots."""
    __tablename__ = "oi_snapshots"

    id = db.Column(db.Integer, primary_key=True)
    timestamp = db.Column(db.DateTime, default=lambda: datetime.now(IST), index=True)
    symbol = db.Column(db.String(20), default="NIFTY", nullable=False)
    expiry = db.Column(db.String(20), nullable=False)
    spot_price = db.Column(db.Float, nullable=False)
    atm_strike = db.Column(db.Float, nullable=False)
    s1_support = db.Column(db.Float, nullable=False)
    s2_support = db.Column(db.Float, nullable=True)
    r1_resistance = db.Column(db.Float, nullable=False)
    r2_resistance = db.Column(db.Float, nullable=True)
    pcr_oi = db.Column(db.Float, nullable=False)
    total_pe_oi = db.Column(db.BigInteger, default=0)
    total_ce_oi = db.Column(db.BigInteger, default=0)
    total_pe_change_oi = db.Column(db.BigInteger, default=0)
    total_ce_change_oi = db.Column(db.BigInteger, default=0)
    net_delta_pe_ce_oi = db.Column(db.BigInteger, default=0)
    writer_momentum = db.Column(db.String(30), default="BALANCED")
    market_regime = db.Column(db.String(30), default="CHOPPY")
    market_bias = db.Column(db.String(20), default="NEUTRAL")
    atm_iv = db.Column(db.Float, default=0.0)

    def to_dict(self):
        return {
            "id": self.id,
            "timestamp": self.timestamp.strftime("%Y-%m-%d %H:%M:%S") if self.timestamp else "",
            "symbol": self.symbol,
            "expiry": self.expiry,
            "spot_price": self.spot_price,
            "atm_strike": self.atm_strike,
            "s1_support": self.s1_support,
            "s2_support": self.s2_support,
            "r1_resistance": self.r1_resistance,
            "r2_resistance": self.r2_resistance,
            "pcr_oi": self.pcr_oi,
            "writer_momentum": self.writer_momentum,
            "market_regime": self.market_regime,
            "market_bias": self.market_bias,
            "atm_iv": self.atm_iv,
        }


