class TradePosition(db.Model):
    """Active and Historical Paper Trading Positions."""
    __tablename__ = "trade_positions"

    id = db.Column(db.Integer, primary_key=True)
    engine_type = db.Column(db.String(20), nullable=False)  # INTRADAY or POSITIONAL
    strategy_id = db.Column(db.String(30), nullable=False)
    strategy_name = db.Column(db.String(60), nullable=False)
    symbol = db.Column(db.String(20), default="NIFTY")
    expiry = db.Column(db.String(20), nullable=False)
    lots = db.Column(db.Integer, default=1)
    quantity = db.Column(db.Integer, default=65)
    
    # Entry Details
    entry_time = db.Column(db.DateTime, default=lambda: datetime.now(IST), index=True)
    entry_spot = db.Column(db.Float, nullable=False)
    entry_net_credit_pts = db.Column(db.Float, nullable=False)
    max_loss_inr = db.Column(db.Float, nullable=False)
    max_profit_inr = db.Column(db.Float, nullable=False)
    target_credit_pts = db.Column(db.Float, nullable=False)  # Profit target (e.g. buy back at 30% credit)
    stop_loss_pts = db.Column(db.Float, nullable=False)       # SL (e.g. 1.5x credit)

    # Current Mark-to-Market
    current_net_debit_pts = db.Column(db.Float, default=0.0)
    current_pnl_inr = db.Column(db.Float, default=0.0)

    # Exit Details
    status = db.Column(db.String(30), default="OPEN", index=True)  # OPEN, CLOSED, STOPPED_OUT, TARGET_HIT, SESSION_EXIT
    exit_time = db.Column(db.DateTime, nullable=True)
    exit_spot = db.Column(db.Float, nullable=True)
    exit_net_debit_pts = db.Column(db.Float, nullable=True)
    exit_reason = db.Column(db.String(100), nullable=True)

    # Financials & Costs
    gross_pnl_inr = db.Column(db.Float, default=0.0)
    transaction_costs_inr = db.Column(db.Float, default=0.0)
    net_pnl_inr = db.Column(db.Float, default=0.0)

    # Itemized Transaction Costs (Entry)
    entry_brokerage_inr = db.Column(db.Float, default=0.0)
    entry_stt_inr = db.Column(db.Float, default=0.0)
    entry_exchange_fees_inr = db.Column(db.Float, default=0.0)
    entry_gst_inr = db.Column(db.Float, default=0.0)
    entry_stamp_duty_inr = db.Column(db.Float, default=0.0)
    entry_sebi_ipft_inr = db.Column(db.Float, default=0.0)

    # Itemized Transaction Costs (Exit)
    exit_brokerage_inr = db.Column(db.Float, default=0.0)
    exit_stt_inr = db.Column(db.Float, default=0.0)
    exit_exchange_fees_inr = db.Column(db.Float, default=0.0)
    exit_gst_inr = db.Column(db.Float, default=0.0)
    exit_stamp_duty_inr = db.Column(db.Float, default=0.0)
    exit_sebi_ipft_inr = db.Column(db.Float, default=0.0)
    
    legs = db.relationship("PositionLeg", backref="position", cascade="all, delete-orphan", lazy="joined")
    mtm_snapshots = db.relationship("PositionMTMSnapshot", backref="position", cascade="all, delete-orphan", lazy="select")
    trade_plan = db.relationship("TradePlan", backref="position", uselist=False, cascade="all, delete-orphan", lazy="joined")

    @property
    def total_risk_with_costs_inr(self) -> float:
        """
        Calculates total committed risk including round-trip transaction costs.
        For an OPEN position, transaction_costs_inr represents entry costs paid;
        closing the position incurs exit costs, so round-trip costs = 2 * transaction_costs_inr.
        For a closed position, transaction_costs_inr already contains realized entry + exit costs.
        """
        if self.status == "OPEN":
            round_trip_costs = 2.0 * (self.transaction_costs_inr or 0.0)
        else:
            round_trip_costs = self.transaction_costs_inr or 0.0
        return round((self.max_loss_inr or 0.0) + round_trip_costs, 2)

    def to_dict(self):
        return {
            "id": self.id,
            "engine_type": self.engine_type,
            "strategy_id": self.strategy_id,
            "strategy_name": self.strategy_name,
            "symbol": self.symbol,
            "expiry": self.expiry,
            "lots": self.lots,
            "quantity": self.quantity,
            "entry_time": self.entry_time.strftime("%Y-%m-%d %H:%M:%S") if self.entry_time else "",
            "entry_spot": self.entry_spot,
            "entry_net_credit_pts": self.entry_net_credit_pts,
            "current_net_debit_pts": self.current_net_debit_pts,
            "current_pnl_inr": self.current_pnl_inr,
            "max_loss_inr": self.max_loss_inr,
            "total_risk_with_costs_inr": self.total_risk_with_costs_inr,
            "max_profit_inr": self.max_profit_inr,
            "status": self.status,
            "exit_time": self.exit_time.strftime("%Y-%m-%d %H:%M:%S") if self.exit_time else None,
            "exit_spot": self.exit_spot,
            "exit_net_debit_pts": self.exit_net_debit_pts,
            "exit_reason": self.exit_reason,
            "gross_pnl_inr": self.gross_pnl_inr,
            "transaction_costs_inr": self.transaction_costs_inr,
            "net_pnl_inr": self.net_pnl_inr,
            "costs_breakdown": {
                "entry": {
                    "brokerage": self.entry_brokerage_inr,
                    "stt": self.entry_stt_inr,
                    "exchange_fees": self.entry_exchange_fees_inr,
                    "gst": self.entry_gst_inr,
                    "stamp_duty": self.entry_stamp_duty_inr,
                    "sebi_ipft": self.entry_sebi_ipft_inr,
                },
                "exit": {
                    "brokerage": self.exit_brokerage_inr,
                    "stt": self.exit_stt_inr,
                    "exchange_fees": self.exit_exchange_fees_inr,
                    "gst": self.exit_gst_inr,
                    "stamp_duty": self.exit_stamp_duty_inr,
                    "sebi_ipft": self.exit_sebi_ipft_inr,
                }
            },
            "legs": [l.to_dict() for l in self.legs],
        }


