"""
app/models.py — SQLAlchemy Database Models for Compact Options Selling Desk
Provides persistent storage for:
- Market & OI Snapshots (OISnapshot)
- Evaluated Strategy Candidates (SignalCandidate)
- Multi-Leg Paper Positions (TradePosition & PositionLeg)
- Risk & Circuit Breaker Events (RiskAuditLog)
"""

from datetime import datetime
from zoneinfo import ZoneInfo
from app.extensions import db

IST = ZoneInfo("Asia/Kolkata")


class OISnapshot(db.Model):
    """Timestamped Open Interest and Market Structure Snapshots."""
    __tablename__ = "oi_snapshots"

    id = db.Column(db.Integer, primary_key=True)
    timestamp = db.Column(db.DateTime, default=lambda: datetime.now(IST), index=True)
    symbol = db.Column(db.String(20), default="NIFTY", nullable=False)
    expiry = db.Column(db.String(20), nullable=False)
    spot_price = db.Column(db.Float, nullable=False)
    atm_strike = db.Column(db.Float, nullable=False)
    s1_support = db.Column(db.Float, nullable=False)
    s2_support = db.Column(db.Float, nullable=True)
    r1_resistance = db.Column(db.Float, nullable=False)
    r2_resistance = db.Column(db.Float, nullable=True)
    pcr_oi = db.Column(db.Float, nullable=False)
    total_pe_oi = db.Column(db.BigInteger, default=0)
    total_ce_oi = db.Column(db.BigInteger, default=0)
    total_pe_change_oi = db.Column(db.BigInteger, default=0)
    total_ce_change_oi = db.Column(db.BigInteger, default=0)
    net_delta_pe_ce_oi = db.Column(db.BigInteger, default=0)
    writer_momentum = db.Column(db.String(30), default="BALANCED")
    market_regime = db.Column(db.String(30), default="CHOPPY")
    market_bias = db.Column(db.String(20), default="NEUTRAL")
    atm_iv = db.Column(db.Float, default=0.0)

    def to_dict(self):
        return {
            "id": self.id,
            "timestamp": self.timestamp.strftime("%Y-%m-%d %H:%M:%S") if self.timestamp else "",
            "symbol": self.symbol,
            "expiry": self.expiry,
            "spot_price": self.spot_price,
            "atm_strike": self.atm_strike,
            "s1_support": self.s1_support,
            "s2_support": self.s2_support,
            "r1_resistance": self.r1_resistance,
            "r2_resistance": self.r2_resistance,
            "pcr_oi": self.pcr_oi,
            "writer_momentum": self.writer_momentum,
            "market_regime": self.market_regime,
            "market_bias": self.market_bias,
            "atm_iv": self.atm_iv,
        }


class SignalCandidate(db.Model):
    """Evaluated Trade Candidates generated by Intraday or Positional Engines."""
    __tablename__ = "signal_candidates"

    id = db.Column(db.Integer, primary_key=True)
    created_at = db.Column(db.DateTime, default=lambda: datetime.now(IST), index=True)
    engine_type = db.Column(db.String(20), nullable=False)  # INTRADAY or POSITIONAL
    strategy_id = db.Column(db.String(30), nullable=False)  # BULL_PUT, BEAR_CALL, IRON_CONDOR, IRON_BUTTERFLY
    strategy_name = db.Column(db.String(60), nullable=False)
    status = db.Column(db.String(20), default="WAIT")       # ELIGIBLE, WAIT, REJECTED_BY_RISK, EXECUTED
    symbol = db.Column(db.String(20), default="NIFTY")
    expiry = db.Column(db.String(20), nullable=False)
    spot_at_eval = db.Column(db.Float, nullable=False)
    short_strike = db.Column(db.Float, nullable=True)
    long_strike = db.Column(db.Float, nullable=True)
    short_strike_2 = db.Column(db.Float, nullable=True)      # For Condor/Butterfly
    long_strike_2 = db.Column(db.Float, nullable=True)
    net_credit_pts = db.Column(db.Float, default=0.0)
    max_profit_inr = db.Column(db.Float, default=0.0)
    max_loss_inr = db.Column(db.Float, default=0.0)
    risk_reward_ratio = db.Column(db.Float, default=0.0)
    confidence_score = db.Column(db.Float, default=0.0)
    rationale = db.Column(db.Text, default="")
    is_executed = db.Column(db.Boolean, default=False)

    def to_dict(self):
        return {
            "id": self.id,
            "created_at": self.created_at.strftime("%Y-%m-%d %H:%M:%S") if self.created_at else "",
            "engine_type": self.engine_type,
            "strategy_id": self.strategy_id,
            "strategy_name": self.strategy_name,
            "status": self.status,
            "symbol": self.symbol,
            "expiry": self.expiry,
            "spot_at_eval": self.spot_at_eval,
            "short_strike": self.short_strike,
            "long_strike": self.long_strike,
            "short_strike_2": self.short_strike_2,
            "long_strike_2": self.long_strike_2,
            "net_credit_pts": self.net_credit_pts,
            "max_profit_inr": self.max_profit_inr,
            "max_loss_inr": self.max_loss_inr,
            "risk_reward_ratio": self.risk_reward_ratio,
            "confidence_score": self.confidence_score,
            "rationale": self.rationale,
            "is_executed": self.is_executed,
        }


class TradePosition(db.Model):
    """Active and Historical Paper Trading Positions."""
    __tablename__ = "trade_positions"

    id = db.Column(db.Integer, primary_key=True)
    engine_type = db.Column(db.String(20), nullable=False)  # INTRADAY or POSITIONAL
    strategy_id = db.Column(db.String(30), nullable=False)
    strategy_name = db.Column(db.String(60), nullable=False)
    symbol = db.Column(db.String(20), default="NIFTY")
    expiry = db.Column(db.String(20), nullable=False)
    lots = db.Column(db.Integer, default=1)
    quantity = db.Column(db.Integer, default=65)
    
    # Entry Details
    entry_time = db.Column(db.DateTime, default=lambda: datetime.now(IST), index=True)
    entry_spot = db.Column(db.Float, nullable=False)
    entry_net_credit_pts = db.Column(db.Float, nullable=False)
    max_loss_inr = db.Column(db.Float, nullable=False)
    max_profit_inr = db.Column(db.Float, nullable=False)
    target_credit_pts = db.Column(db.Float, nullable=False)  # Profit target (e.g. buy back at 30% credit)
    stop_loss_pts = db.Column(db.Float, nullable=False)       # SL (e.g. 1.5x credit)

    # Current Mark-to-Market
    current_net_debit_pts = db.Column(db.Float, default=0.0)
    current_pnl_inr = db.Column(db.Float, default=0.0)

    # Exit Details
    status = db.Column(db.String(30), default="OPEN", index=True)  # OPEN, CLOSED, STOPPED_OUT, TARGET_HIT, SESSION_EXIT
    exit_time = db.Column(db.DateTime, nullable=True)
    exit_spot = db.Column(db.Float, nullable=True)
    exit_net_debit_pts = db.Column(db.Float, nullable=True)
    exit_reason = db.Column(db.String(100), nullable=True)

    # Financials & Costs
    gross_pnl_inr = db.Column(db.Float, default=0.0)
    transaction_costs_inr = db.Column(db.Float, default=0.0)
    net_pnl_inr = db.Column(db.Float, default=0.0)
    
    legs = db.relationship("PositionLeg", backref="position", cascade="all, delete-orphan", lazy="joined")

    def to_dict(self):
        return {
            "id": self.id,
            "engine_type": self.engine_type,
            "strategy_id": self.strategy_id,
            "strategy_name": self.strategy_name,
            "symbol": self.symbol,
            "expiry": self.expiry,
            "lots": self.lots,
            "quantity": self.quantity,
            "entry_time": self.entry_time.strftime("%Y-%m-%d %H:%M:%S") if self.entry_time else "",
            "entry_spot": self.entry_spot,
            "entry_net_credit_pts": self.entry_net_credit_pts,
            "current_net_debit_pts": self.current_net_debit_pts,
            "current_pnl_inr": self.current_pnl_inr,
            "max_loss_inr": self.max_loss_inr,
            "max_profit_inr": self.max_profit_inr,
            "status": self.status,
            "exit_time": self.exit_time.strftime("%Y-%m-%d %H:%M:%S") if self.exit_time else None,
            "exit_reason": self.exit_reason,
            "gross_pnl_inr": self.gross_pnl_inr,
            "transaction_costs_inr": self.transaction_costs_inr,
            "net_pnl_inr": self.net_pnl_inr,
            "legs": [l.to_dict() for l in self.legs],
        }


class PositionLeg(db.Model):
    """Individual Option Leg of an Active or Historical Spread."""
    __tablename__ = "position_legs"

    id = db.Column(db.Integer, primary_key=True)
    position_id = db.Column(db.Integer, db.ForeignKey("trade_positions.id"), nullable=False, index=True)
    symbol = db.Column(db.String(50), nullable=False)
    strike = db.Column(db.Float, nullable=False)
    option_type = db.Column(db.String(10), nullable=False)  # CE or PE
    action = db.Column(db.String(10), nullable=False)       # SELL or BUY
    quantity = db.Column(db.Integer, nullable=False)
    entry_price = db.Column(db.Float, nullable=False)
    current_price = db.Column(db.Float, default=0.0)
    exit_price = db.Column(db.Float, nullable=True)

    def to_dict(self):
        return {
            "id": self.id,
            "symbol": self.symbol,
            "strike": self.strike,
            "option_type": self.option_type,
            "action": self.action,
            "quantity": self.quantity,
            "entry_price": self.entry_price,
            "current_price": self.current_price,
            "exit_price": self.exit_price,
        }


class RiskAuditLog(db.Model):
    """Audit Log for Portfolio Risk Evaluations & Circuit Breakers."""
    __tablename__ = "risk_audit_logs"

    id = db.Column(db.Integer, primary_key=True)
    timestamp = db.Column(db.DateTime, default=lambda: datetime.now(IST), index=True)
    engine_type = db.Column(db.String(20), nullable=False)
    event_type = db.Column(db.String(40), nullable=False)   # TRADE_APPROVED, TRADE_BLOCKED, CIRCUIT_BREAKER, COOLDOWN
    decision = db.Column(db.String(20), nullable=False)     # APPROVED or BLOCKED
    trade_risk_inr = db.Column(db.Float, default=0.0)
    current_portfolio_risk_inr = db.Column(db.Float, default=0.0)
    reason = db.Column(db.Text, nullable=False)

    def to_dict(self):
        return {
            "id": self.id,
            "timestamp": self.timestamp.strftime("%Y-%m-%d %H:%M:%S") if self.timestamp else "",
            "engine_type": self.engine_type,
            "event_type": self.event_type,
            "decision": self.decision,
            "trade_risk_inr": self.trade_risk_inr,
            "current_portfolio_risk_inr": self.current_portfolio_risk_inr,
            "reason": self.reason,
        }
